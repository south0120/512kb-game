const cnv = (w, h) => { const c = document.createElement('canvas'); c.width = w; c.height = h; return c; };
// pal: データの数字→色文字。mir=1 なら左半分だけ描いて左右対称にする
function mk(pal, d, w = 8, mir = 1) {
  d = d.replace(/\s/g, '');
  const c = cnv(mir ? w * 2 : w, d.length / w), x = c.getContext('2d');
  d.length % w && console.error('art', pal, d.length);
  for (let i = 0; i < d.length; i++) if (d[i] != '.') {
    const px = i % w, py = i / w | 0;
    x.fillStyle = C(pal[d[i]]);
    x.fillRect(px, py, 1, 1);
    mir && x.fillRect(w * 2 - 1 - px, py, 1, 1);
  }
  return c;
}
