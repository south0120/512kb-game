// ヌシ (32x32) は だ円の あつまりから作る
function blob(parts, pal, eyes, gold) {
  const c = cnv(32, 32), x = c.getContext('2d');
  const at = (px, py) => parts.some(p => ((px + .5 - p[0]) / p[2]) ** 2 + ((py + .5 - p[1]) / p[3]) ** 2 < 1);
  for (let py = 0; py < 32; py++) for (let px = 0; px < 32; px++) {
    const v = at(px, py) ? !at(px, py - 1) || !at(px - 1, py) ? 3 : !at(px, py + 1) || !at(px + 1, py) ? 1 : 2
      : at(px - 1, py) || at(px + 1, py) || at(px, py - 1) || at(px, py + 1) ? 0 : -1;
    if (v >= 0) { x.fillStyle = C(pal[v]); x.fillRect(px, py, 1, 1); }
  }
  for (const [ex, ey] of eyes) {
    x.fillStyle = C(gold ? 'e' : 'r'); x.fillRect(ex, ey, 3, 3);
    x.fillStyle = C(gold ? 'r' : '0'); x.fillRect(ex + 1, ey + 1, 1, gold ? 1 : 2);
  }
  return c;
}
