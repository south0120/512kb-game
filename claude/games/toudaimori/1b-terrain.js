// マスの 4つの へりの うち side (0した 1うえ 2ひだり 3みぎ) がわに、ながさ16 あつさ h の おびを かく
const edge = (g, x, y, s, k, h, len = 2) => s < 2 ? g.fillRect(x + k, s ? y : y + 16 - h, len, h) : g.fillRect(s == 2 ? x : x + 16 - h, y + k, h, len);
const shade = (g, x, y, w, h, a) => { g.globalAlpha = a; g.fillStyle = C('0'); g.fillRect(x, y, w, h); g.globalAlpha = 1; };
function ground(g, ch, i, x, y) {
  const v = hv(i);
  if (ch == ' ') g.drawImage(floorT[th], x, y);
  else if (ch == ',') { g.drawImage(SAND, x, y); v < 24 && g.drawImage(SHELL, x + 3 + v % 9, y + 4 + v % 7); }
  else if (ch == '_') g.drawImage(PATH, x, y);
  else if (ch == '=') {
    g.drawImage(BRIDGE, x, y);
    for (const s of [0, 1]) if (nb(i, 0, SY[s]) == '~') { g.fillStyle = C('B'); edge(g, x, y, s, 0, 3, 16); g.fillStyle = C('H'); edge(g, x, y, s, 0, 1, 16); }
  } else {
    g.drawImage(GRASS, x, y);
    if (ch == 'j' || v < 14) g.drawImage(BLOOM, x, y); else if (v < 70) g.drawImage(TUFT, x, y);
  }
  // すなや みちには くさが はみだす
  if (ch == ',' || ch == '_') for (let s = 0; s < 4; s++) if ('.j"T*'.includes(nb(i, SX[s], SY[s]))) for (let k = 0; k < 16; k += 2) { g.fillStyle = C(hv(i, s * 16 + k) & 1 ? '6' : '7'); edge(g, x, y, s, k, 1 + hv(i, s * 16 + k) % 3); }
  // たかい ものの したには かげ
  if (i > 9 && '#MHw'.includes(cur[i - 10])) shade(g, x, y, 16, 4, .3);
}
function drawTile(g, ch, i, x, y, f) {
  const below = nb(i, 0, 1);
  if (ch == '~') {
    g.drawImage(WATER[f], x, y);
    for (let s = 0; s < 4; s++) if (!'~=o'.includes(nb(i, SX[s], SY[s]))) {
      if (s == 1) shade(g, x, y, 16, 5, .25);
      for (let k = 0; k < 16; k += 2) { const a = (k / 2 + f + hv(i, s)) % 3; g.fillStyle = C(a ? 'u' : '3'); a < 2 && edge(g, x, y, s, k, 1); g.fillStyle = C('3'); a || edge(g, x, y, s, k, 2); }
    }
    return;
  }
  if (ch == 'T') {
    g.drawImage([[1, 0], [-1, 0], [0, 1], [0, -1]].every(([a, b]) => nb(i, a, b) == 'T') ? DEEP : GRASS, x, y);
    return g.drawImage(TREE, x, y);
  }
  if (ch == 'M') {
    if (below != 'M') return g.drawImage(ROCKFACE, x, y);
    g.drawImage(ROCKTOP, x, y);
    for (let s = 0; s < 4; s++) if (nb(i, SX[s], SY[s]) != 'M') { g.fillStyle = C(s % 2 ? 'g' : 'a'); edge(g, x, y, s, 0, 2, 16); }
    return;
  }
  if (ch == '#') {
    if (!th) {      // とうだいの しましま
      g.drawImage(TOWER[(i / 10 | 0) & 1], x, y);
      nb(i, -1, 0) == '#' || shade(g, x, y, 2, 16, .15);
      nb(i, 1, 0) == '#' || shade(g, x + 12, y, 4, 16, .3);
      return;
    }
    if (below != '#' && !isW(below)) return g.drawImage(wallF[th], x, y);
    g.fillStyle = C(THEME[th][0]); g.fillRect(x, y, 16, 16);
    g.fillStyle = C(THEME[th][1]);
    for (let s = 0; s < 4; s++) '#'.includes(nb(i, SX[s], SY[s])) || edge(g, x, y, s, 0, 1, 16);
    return;
  }
  if (ch == '^') {
    g.drawImage(ROOF, x, y);
    nb(i, 0, -1) == '^' || (g.fillStyle = C('C'), g.fillRect(x, y, 16, 1));
    nb(i, -1, 0) == '^' || shade(g, x, y, 1, 16, .35);
    nb(i, 1, 0) == '^' || shade(g, x + 14, y, 2, 16, .35);
    return;
  }
  if (ch == 'H' || ch == 'w') { g.drawImage(HWALL, x, y); ch == 'w' && g.drawImage(WINDOW, x + 4, y + 5); return; }
  if (ch == 'Y') return g.drawImage(tl[G.won ? 'Y' : 'y'], x, y);
  if (ch == '*' || ch == 'd' || ch == 'D') return g.drawImage(tl[ch], x, y);
  if (isW(ch)) {
    if (ch == '6' || ch == '7') { g.drawImage(floorT[th], x, y); return g.drawImage(tl.s, x, y); }   // かいだん
    if (th) { g.fillStyle = C(THEME[th][0]); g.fillRect(x, y, 16, 16); return g.drawImage(th == 4 ? tl.door : CAVE, x, y); }
    return g.drawImage(ch == '2' || ch == '3' ? CAVE : WDOOR, x, y);
  }
  if (FLR.includes(ch)) return ground(g, ch, i, x, y);
  // もの・ひと: じめんの うえに かげを おとして かく
  const u = ch == 'o' ? fill(i) : under(i);
  u == '~' ? g.drawImage(WATER[f], x, y) : ground(g, u, i, x, y);
  if (ch == '?') return;
  'xhkfu'.includes(ch) || shade(g, x + 2, y + 13, 12, 2, .25);
  if (ch == 'I') { g.drawImage(tl.i, x, y); return g.drawImage(FLAME[f], x, y); }
  g.drawImage(NPC[ch] || tl[ch], x, y);
  ch == 'f' && g.drawImage(FLAME[f], x, y + 6);
}
